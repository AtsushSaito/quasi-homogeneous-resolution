#!/usr/bin/env python3
"""Independently verify the unit-ideal certificates: expand sum_i g_i h_i over F_p and check it is 1.

This does not use Macaulay2, Groebner bases, or any computer algebra library -- only integer
arithmetic on exponent vectors.

WHAT THIS PROVES, EXACTLY.  For each block it checks that the cofactors g_i and the polynomials
h_i printed in the certificate satisfy sum_i g_i h_i = 1 in F_p[...].  That establishes, without
trusting any Groebner engine, that the ideal generated by those h_i is the unit ideal.

WHAT IT DOES NOT PROVE.  It does not check that the h_i are the generators of the ideal whose
smoothness the certificate claims -- they are read from the certificate, not recomputed from the
fan and f.  If certify.m2 divided out the wrong monomial and emitted the partials of some other
polynomial, this script would still print OK.  Closing that gap means recomputing the strict
transform in each chart from the fan file, which this script deliberately does not do.
"""
import sys, re, glob, collections

TERM = re.compile(r'([+-]?)([^+-]+)')
FACTOR = re.compile(r'^(?:([A-Za-z]+)_(\d+)(?:\^(\d+))?|(\d+))$')

def parse(s, p):
    """polynomial -> dict {exponent tuple as dict var->exp : coeff mod p}"""
    s = s.replace(' ', '')
    out = collections.defaultdict(int)
    for sign, term in TERM.findall(s):
        if not term: continue
        coeff = -1 if sign == '-' else 1
        exps = collections.Counter()
        for fac in term.split('*'):
            m = FACTOR.match(fac)
            if not m: raise ValueError('cannot parse factor %r in %r' % (fac, s))
            if m.group(4) is not None:
                coeff *= int(m.group(4))
            else:
                # Key on the name as well as the subscript.  Keying on the subscript alone made
                # xx_0 and yy_0 the same variable, so a certificate over a ring with two families
                # of variables could verify a false identity.
                exps[(m.group(1), int(m.group(2)))] += int(m.group(3) or 1)
        out[tuple(sorted(exps.items()))] = (out[tuple(sorted(exps.items()))] + coeff) % p
    return {k: v for k, v in out.items() if v % p}

def mul(a, b, p):
    out = collections.defaultdict(int)
    for ea, ca in a.items():
        for eb, cb in b.items():
            e = collections.Counter(dict(ea)); e.update(dict(eb))
            out[tuple(sorted(e.items()))] = (out[tuple(sorted(e.items()))] + ca * cb) % p
    return {k: v for k, v in out.items() if v % p}

def add(a, b, p):
    out = collections.defaultdict(int, a)
    for e, c in b.items(): out[e] = (out[e] + c) % p
    return {k: v for k, v in out.items() if v % p}

def splitlist(s):
    """split '{a, b, c}' at top level commas"""
    s = s.strip()[1:-1]
    parts, depth, cur = [], 0, ''
    for ch in s:
        if ch in '({[': depth += 1
        elif ch in ')}]': depth -= 1
        if ch == ',' and depth == 0: parts.append(cur); cur = ''
        else: cur += ch
    if cur.strip(): parts.append(cur)
    return [x.strip() for x in parts]

def verify(path):
    lines = open(path).read().splitlines()
    p = int(next(l for l in lines if l.startswith('characteristic')).split()[1])
    nblocks = nok = 0
    hs = gs = None
    for l in lines:
        if l.strip().startswith('h = '): hs = splitlist(l.split('h = ', 1)[1])
        elif l.strip().startswith('g = '):
            gs = splitlist(l.split('g = ', 1)[1])
            nblocks += 1
            tot = {}
            for h, g in zip(hs, gs):
                tot = add(tot, mul(parse(h, p), parse(g, p), p), p)
            if tot == {(): 1 % p}: nok += 1
            else: print('  FAILED block %d in %s : sum = %r' % (nblocks, path, tot))
    return nblocks, nok, p

total = okall = nbroken = 0
for path in sorted(glob.glob(sys.argv[1] if len(sys.argv) > 1 else 'data/certificates/*.cofactors.txt')):
    try:
        nb, nk, p = verify(path)
    except Exception as exc:                       # one bad token must not discard the whole run
        nbroken += 1
        print('%-50s COULD NOT BE VERIFIED: %s' % (path.split('/')[-1], exc))
        continue
    print('%-50s char %d  %d/%d identities verified' % (path.split('/')[-1], p, nk, nb))
    total += nb; okall += nk
ok = okall == total and total and not nbroken
print('TOTAL: %d/%d identities verified by expansion%s%s'
      % (okall, total,
         '' if not nbroken else ', %d file(s) unreadable' % nbroken,
         '  -- OK' if ok else '  -- FAILURES'))
sys.exit(0 if ok else 1)
