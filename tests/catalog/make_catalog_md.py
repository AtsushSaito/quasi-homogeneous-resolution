#!/usr/bin/env python3
"""Generate docs/CATALOG.md from the tables in tests/catalog/ (hypersurfaces.tsv, cyclic.tsv,
fans.tsv, switches.tsv).  Run after any change of a table:

  python3 tests/catalog/make_catalog_md.py
"""
import csv, os, re
from collections import Counter, defaultdict

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))
def rd(name): return list(csv.DictReader(open(os.path.join(here, name)), delimiter='\t'))
hyp, cyc, fans = rd('hypersurfaces.tsv'), rd('cyclic.tsv'), rd('fans.tsv')
sw = rd('switches.tsv') if os.path.exists(os.path.join(here, 'switches.tsv')) else []

def anchor(s): return re.sub(r'[^a-z0-9 -]', '', s.lower()).replace(' ', '-')
def md(s): return s.replace('|', '\\|')

out = []
w = out.append
w('# Catalog of resolved examples')
w('')
w('*Generated by `tests/catalog/make_catalog_md.py` from the tables in `tests/catalog/`; do not edit by hand.*')
w('')
w('Each entry has its input, the expected result and an evidence class (below).  The same tables drive the test runners, so every row marked '
  '`ci` below is re-checked by `sh tests/run_ci.sh`, and every row can be re-checked with `sh tests/run_all.sh`.')
w('')
w('## How to read the evidence column')
w('')
w('| code | meaning |')
w('|---|---|')
w('| **L** | the expected value agrees with a classical value stored with the sample (dual graph of a rational double point; genus and self-intersection of a simple elliptic singularity; Hirzebruch-Jung continued fraction). The classical statements are quoted from standard theory, they were not re-derived here, and for characteristic p they are what the computation is compared against, not an independent proof. |')
w('| **X** | agreement of two routes inside this repository: the prediction from the stabiliser strata (`qhPredict`) and the explicit toric resolution of the weighted blow-up (`toricResolve`). |')
w('| **V** | an independent certificate exists in `data/certificates/` (exact test that the toric map is proper, unit-ideal identities re-expanded by `scripts/verify_cofactors.py`, exact rational test of projectivity by `scripts/projectivity_exact.py`). |')
w('| **O** | output of the implementation only; no independent value is known to the author. |')
w('| **N** | negative example: hypothesis (A4) fails.  The runner re-computes this with a plain Jacobian computation. |')
w('')
w('"Confirmed" in this catalog means exactly the codes L, X or V, never O.  No row of the recorded run has a '
  'verdict MISMATCH, TORIC-FAIL, PREDICT-FAIL or CRASH (`results/summary.tsv`, 440 rows: '
  '361 CONFIRM, 79 SKIP).')
w('')
w('## How to run')
w('')
w('| what | command | time |')
w('|---|---|---|')
w('| fast set (all `ci` rows, all unit tests, the package check) | `sh tests/run_ci.sh` | about 5 minutes |')
w('| everything in the tables, including the heavy rows | `sh tests/run_all.sh` | about 40 minutes |')
w('| one hypersurface | `ONLY=E8_p2 M2 --script tests/catalog/run_hypersurfaces.m2` | seconds |')
w('| the 16 readings of Bergh\'s step A2 on the hard cone | `CASES=rank3 sh scripts/sweep_a2.sh` | up to an hour |')
w('')
w('Times were measured on one laptop (Macaulay2 1.26.06) and are only a guide.')
w('')

# ---------------------------------------------------------------- table of contents
cats = defaultdict(list)
for r in hyp: cats[r['category']].append(r)
w('## Contents')
w('')
w('- [Cyclic quotient surface singularities 1/r(1,q)](#cyclic-quotient-surface-singularities) -- %d rows' % len(cyc))
w('- [Higher-dimensional simplicial cones (Bergh\'s algorithm)](#higher-dimensional-simplicial-cones) -- %d rows' % len(fans))
if sw: w('- [Dependence on the choices left open in step A2](#the-choices-left-open-in-step-a2) -- %d rows' % len(sw))
for k in sorted(cats):
    w('- [%s](#%s) -- %d rows' % (k, anchor(k), len(cats[k])))
w('- [Index by feature](#index-by-feature)')
w('')

# ---------------------------------------------------------------- cyclic
w('## Cyclic quotient surface singularities')
w('')
w('Input: the cone spanned by (0,1) and (r,-q) in Z^2, that is the singularity 1/r(1,q), with trivial labels.  '
  'Expected: after Bergh\'s Algorithm B the fan is smooth and, after contracting (-1)-curves, the chain of exceptional '
  'curves has self-intersections -b_1, ..., -b_k where r/q = [b_1, ..., b_k] is the Hirzebruch-Jung continued fraction '
  '(evidence **L**: classical; the table was computed independently in Python with exact integers by '
  '`tests/catalog/gen_cyclic.py`, and re-evaluated to r/q by `check_catalog.py`).  '
  'Command: `M2 --script tests/catalog/run_cyclic.m2` (rows with r <= 12, about 15 s) or `TIER=all M2 --script tests/catalog/run_cyclic.m2` (r <= 16, about 1 minute).')
w('')
w('Notation of the chain: `{3, 2}` means two curves of self-intersection -3 and -2.  Special cases: 1/r(1,1) is the cone over the rational normal curve of degree r (one curve, self-intersection -r); 1/r(1,r-1) is the A_{r-1} singularity (r-1 curves of self-intersection -2).')
w('')
w('| r | q | HJ chain | curves | tier |')
w('|---|---|---|---|---|')
for r in cyc: w('| %s | %s | `%s` | %s | %s |' % (r['r'], r['q'], r['expected_hj'], r['expected_curves'], r['tier']))
w('')

# ---------------------------------------------------------------- fans
w('## Higher-dimensional simplicial cones')
w('')
w('Input: a stacky fan given by one simplicial cone (rays, labels).  Expected: multiplicity of the cone before; number of rays and of maximal cones of the smooth output.  '
  'The runner also checks, with exact integer arithmetic independent of the package, that every maximal cone of the output has determinant +-1, that every output ray lies in the original cone, and that the original rays are kept.  '
  'Evidence **L** (single blow-up of 1/2(1,...,1), classical) or **O** (counts are regression values).  '
  'Command: `M2 --script tests/catalog/run_fans.m2`, about 5 s; heavy rows with `TIER=all`.')
w('')
w('| id | rays | labels | multiplicity | rays after | maximal cones after | evidence | tier | note |')
w('|---|---|---|---|---|---|---|---|---|')
for r in fans:
    w('| %s | `%s` | `%s` | %s | %s | %s | %s | %s | %s |' % (r['id'], r['rays'], r['labels'], r['mult_before'], r['rays_after'], r['cones_after'], r['evidence'], r['tier'], md(r['note'])))
w('')

# ---------------------------------------------------------------- switches
if sw:
    w('## The choices left open in step A2')
    w('')
    w('Bergh\'s step A2 does not fix four things (see the Caveat in `package/ToricDestackification.m2`).  The research code `src/StackyFan.m2` exposes them as switches (`psiOrder`, `a2Extreme`, `a2Key`, `a2Interior`) and `scripts/sweep_a2.sh` runs all 2^4 = 16 readings.  Termination and correctness do not depend on the reading; the cost does.')
    w('')
    w('| case | readings that finished | detail | evidence | time limit | source |')
    w('|---|---|---|---|---|---|')
    for r in sw: w('| %s | %s | %s | %s | %s | %s |' % (r['case'], r['finished'], md(r['detail']), r['evidence'], r['limit'], md(r['source'])))
    w('')

# ---------------------------------------------------------------- hypersurfaces
def result(r):
    if r['expected_verdict'] == 'SKIP': return 'A4 fails (not isolated)'
    parts = []
    if r['expected_curves'] != '-':
        parts.append('%s curves' % r['expected_curves'])
        if r['expected_arms'] != '-': parts.append('arms %s' % r['expected_arms'].replace(' ', ''))
        parts.append('centre %s' % r['expected_centre_self'])
        parts.append('g=%s' % r['expected_genus'])
    else:
        parts.append('strata orders %s' % r['expected_strata_orders'].replace(' ', ''))
    return ', '.join(parts)

intro = {
 'S1': 'Rational double points A_n, D_n, E_n written in quasi-homogeneous form, in characteristics 2, 3, 5, 7 (in characteristic 2 the forms D_n^0, E_n^0 of Artin).  Expected: the resolution graph is the ADE Dynkin diagram, all curves of self-intersection -2.  The *arms* are the lengths of the three (or fewer) branches of the star-shaped graph around the central curve (the image of Proj R); "alt weights" are different weightings of the same equation, which give different centres.',
 'S2': 'Brieskorn-Pham surfaces x^a + y^b + z^c, 2 <= a <= b <= c <= 7, in characteristics 2, 3, 5, 7.  No classical value is stored; the expected values are the prediction by the stabiliser strata, confirmed (X) by the toric computation.',
 'S3': 'The 14 exceptional unimodal singularities of Arnold (quasi-homogeneous representatives), characteristics 2, 3, 5, 7.  Rows with A4 false are the characteristic-dependent degenerations.',
 'S4': 'Simple elliptic singularities E~6, E~7, E~8.  Expected: one elliptic curve (genus 1) with self-intersection -3, -2, -1; in small characteristic the equation is no longer isolated, which is recorded as a negative example.',
 'H3': 'Threefolds (n = 4 variables): Brieskorn-Pham type and the mixed examples where p divides a weight, the degree or the stabiliser order.  Only the stabiliser orders are tabulated (no dual graph in dimension 3).',
 'H4': 'Fourfolds (n = 5 variables), same conventions.',
 'H5': 'Dimensions 5 and 6 (n = 6, 7 variables).',
}
w('## Hypersurfaces')
w('')
w('Category names: S1-S4 are surfaces (3 variables), H3-H5 are higher-dimensional hypersurfaces (4 variables = threefolds, 5 = fourfolds, 6-7 = dimensions 5 and 6).')
w('')
w('Input: a polynomial f in F_p[x,y,z,u,v,s,t] (first n variables), weights w with f quasi-homogeneous of the given degree, X = Spec F_p[x]/(f), assumed smooth away from the vertex (A4).  '
  'Expected: the verdict of `qhVerify` (CONFIRM = prediction and explicit resolution agree; SKIP = A4 fails), the orders r of the stabiliser strata, and for surfaces the resolution graph.  '
  'Columns: *features* lists p|w_i, p|d, p|r (p divides the order of a stabiliser: the quotient stack is not Deligne-Mumford) and "alt weights"; *result* is `curves, arms, centre self-intersection, genus`; *s* is the time recorded when the corpus was run.  '
  'Rows with tier `ci` are run by `tests/catalog/run_hypersurfaces.m2`; the others by `TIER=all` or `ONLY=<id>`.')
w('')
for k in sorted(cats):
    rs = cats[k]
    w('### %s' % k)
    w('')
    w(intro[k.split()[0]])
    w('')
    ev = Counter(); [ev.update(r['evidence']) for r in rs]
    w('%d rows; evidence: %s.' % (len(rs), ', '.join('%s %d' % (c, ev[c]) for c in 'LXVON' if ev[c])))
    w('')
    w('| id | p | equation | weights | deg | features | result | evidence | tier | s |')
    w('|---|---|---|---|---|---|---|---|---|---|')
    for r in rs:
        w('| %s | %s | `%s` | `%s` | %s | %s | %s | %s | %s | %s |' % (r['id'], r['p'], md(r['equation']), r['weights'].replace(' ', ''),
          r['degree'], md(r['features']), result(r), r['evidence'], r['tier'], r['seconds_when_recorded']))
    w('')

# ---------------------------------------------------------------- index by feature
w('## Index by feature')
w('')
w('Where to look for the cases that are special in positive characteristic.  Ids refer to the tables above.')
w('')
feat = defaultdict(list)
for r in hyp:
    if r['expected_verdict'] == 'SKIP': feat['A4 fails (negative examples)'].append(r['id'])
    else:
        for f in r['features'].split(';'):
            if f != '-': feat[f].append(r['id'])
    if 'V' in r['evidence']: feat['has an independent certificate (V)'].append(r['id'])
for f in sorted(feat):
    ids = feat[f]
    w('- **%s** (%d): %s' % (f, len(ids), ', '.join(ids) if len(ids) <= 40 else ', '.join(ids[:40]) + ', ... (%d more; filter the tables by this feature)' % (len(ids) - 40)))
w('')
open(os.path.join(root, 'docs/CATALOG.md'), 'w').write('\n'.join(out) + '\n')
print('wrote docs/CATALOG.md,', len(out), 'lines')
